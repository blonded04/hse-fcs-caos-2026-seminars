#include <stdio.h>

int main(void) {
    for (;;) {
        /* На некоторых системах (например, msys2) отдельные вызовы
           вывода плохо перемешиваются между собой, поэтому здесь
           строка печатается двумя вызовами. */
        printf("Hello ");
        printf("World\n");
    }
    for (;;) {
        printf("2 + 2 = ");
        printf("4\n");
    }
    return 0;
}
