; Подпрограмма должна вычислить выражение sqrt(x^4 + y^4) и сохранить
; результат по указателю r.
; Подпрограмма должна соблюдать стандартные соглашения о вызовах.
; Должен использоваться стандартный пролог и эпилог функции.
; Для вычислений используйте SSE.
; Например, если x == 4.0, y == 3.0, то по указателю r должно быть
; записано значение sqrt(337.0).
; Напомним, что первые 8 параметров вещественных типов float или double передаются на регистрах xmm0 ... xmm7,
; последующие вещественные аргументы передаются в стеке.

        .intel_syntax noprefix
        .global okay
okay:
    push rbp
    mov rbp, rsp

    mulsd xmm0, xmm0
    mulsd xmm0, xmm0
    mulsd xmm1, xmm1
    mulsd xmm1, xmm1
    addsd xmm0, xmm1
    sqrtsd xmm0, xmm0
    movsd [rdi], xmm0

    pop rbp
    ret
